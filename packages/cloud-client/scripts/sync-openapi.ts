// Regenerates src/generated/v1.ts from Dexto's served /v1 OpenAPI document:
//   pnpm --filter @dexto/cloud-client sync [url]
// The document is the public client contract (DEXTO-2033); operation ids, methods and paths stay
// stable within /v1.

import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import ts from 'typescript';

const url = process.argv[2] ?? 'https://api.dexto.ai/v1/openapi.json';
const response = await fetch(url);
if (!response.ok) throw new Error(`${url} answered HTTP ${response.status}`);
// openapi-typescript writes the recursive JsonValue schema as components["schemas"]["JsonValue"]
// inside its own definition, which TypeScript rejects (TS2502). A type alias may refer to itself, so
// the schema becomes a reference to one declared at the top of the file.
const ast = await openapiTS(await response.text(), {
    transform: (_schema, { path }) =>
        path === '#/components/schemas/JsonValue'
            ? ts.factory.createTypeReferenceNode('JsonValue')
            : undefined,
});
const jsonValue =
    'export type JsonValue = boolean | number | string | null | JsonValue[] | { [key: string]: JsonValue };';
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/generated/v1.ts');
await writeFile(
    target,
    `// Generated by scripts/sync-openapi.ts from ${url}. Do not edit.\n\n${jsonValue}\n\n${astToString(ast)}`
);
console.log(`Wrote ${target}`);
