/** Rows of cut type, always 3 tall. */
export const CUT_ROWS = 3;

function glyphFor(ch: string): readonly string[] {
    return CUT[ch] ?? CUT[' '] ?? [];
}

/** Cell width of `text` in cut type: glyphs plus one blank column between them. */
export function cutWidth(text: string): number {
    const chars = [...text.toUpperCase()];
    if (chars.length === 0) return 0;
    return chars.reduce((w, ch) => w + (glyphFor(ch)[0]?.length ?? 0) + 1, -1);
}

/** The 3 text lines that draw `text` in cut type (half blocks, trailing spaces kept). */
export function cutLines(text: string): string[] {
    const lines = ['', '', ''];
    [...text.toUpperCase()].forEach((ch, i) => {
        const g = glyphFor(ch);
        const gw = g[0]?.length ?? 0;
        for (let r = 0; r < CUT_ROWS; r++) {
            let row = i === 0 ? '' : ' ';
            for (let c = 0; c < gw; c++) {
                const top = g[r * 2]?.[c] === '#';
                const bottom = g[r * 2 + 1]?.[c] === '#';
                row += top && bottom ? '█' : top ? '▀' : bottom ? '▄' : ' ';
            }
            lines[r] += row;
        }
    });
    return lines;
}
